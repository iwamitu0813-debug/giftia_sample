-- concern_keywords.sql — 困りごと → 説明書きで探す言葉 の対応表（DR-01）
-- 1回だけ実行する（python setup_concern_keywords.py）。何度実行しても同じ行は増えない。
-- 言葉を足したいときは、この表に1行足すだけでよい（プログラムは触らない）。

CREATE TABLE IF NOT EXISTS concern_keywords (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  concern_label VARCHAR(50) NOT NULL,  -- Q1の困りごと（画面の選択肢と同じ文言）
  keyword       VARCHAR(50) NOT NULL,  -- 説明書きで探す言葉（1行に1語）
  sort_order    INT NOT NULL,          -- 画面に出す順番
  UNIQUE KEY uq_concern_keyword (concern_label, keyword)
);

